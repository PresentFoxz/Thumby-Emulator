int32_t to_fixed(float a) { return (int32_t)(a * (float)FP24X8_ONE); }
float from_fixed(int32_t a) { return (float)a / (float)FP24X8_ONE; }

int32_t div_opp(int32_t value) {
    if (value == 0) return 0;

    int negative = 0;
    if (value < 0) {
        negative = 1;
        value = -value;
    }

    int shift = 0;
    while (value >= 520) {
        value >>= 1;
        shift++;
    }

    int32_t reciprocal = DIV_LUT[value];
    reciprocal >>= shift;
    if (negative) reciprocal = -reciprocal;

    return reciprocal;
}

int32_t mul_opp(int32_t value, int32_t divisor) {
    if (divisor == 0) return 0;

    int32_t reciprocal = div_opp(divisor);
    return (int32_t)(((int64_t)value * (int64_t)reciprocal) >> 16);
}

int32_t fixed_mul(int32_t a, int32_t b) { return (int32_t)(((int64_t)a * (int64_t)b) >> FIXED_BITS); }

int32_t fixed_div(int32_t a, int32_t b) {
    if (b == 0) return 0;
    return (int32_t)(((int64_t)a << FIXED_BITS) / b);
}

